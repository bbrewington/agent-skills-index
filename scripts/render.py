#!/usr/bin/env python3
"""
render.py

Markdown the bot commits under generated/ (ADR 0002): the upstream changelog, one file per month,
newest first, and INDEX.md, curated repos grouped by use-context.

Usage (regenerate INDEX.md from tracked.yml without running a sync):
    python scripts/render.py
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).parent.parent
GENERATED_DIR = ROOT / "generated"
CHANGELOG_DIR = GENERATED_DIR / "changelog"
INDEX_FILE = GENERATED_DIR / "INDEX.md"

VERDICT_ORDER = {"adopt": 0, "watch": 1}


def _by_verdict(entries: list[dict]) -> list[dict]:
    return sorted(entries, key=lambda e: (VERDICT_ORDER.get(e.get("verdict"), 2), e["repo"].lower()))


# -----------------------------------------------------------------------
# Changelog
# -----------------------------------------------------------------------

def render_entries(changes: list[dict], date: str) -> str:
    lines = [f"## {date}", ""]
    for c in _by_verdict(changes):
        lines.append(f"### {c['repo']} ({c['verdict']}) - [compare]({c['compare_url']})")
        lines.append("")
        for release in c.get("releases", []):
            lines.append(f"- Release [{release['name']}]({release['url']}) (`{release['tag']}`)")
        if c.get("tags"):
            lines.append("- New tags: " + ", ".join(f"`{t}`" for t in c["tags"]))
        for commit in c.get("commits", []):
            lines.append(f"- [`{commit['sha'][:7]}`]({commit['url']}) {commit['message']}")
        lines.append("")
    return "\n".join(lines)


def write_changelog(changes: list[dict], directory: Path, date: str) -> Path | None:
    """Insert this run's entries at the top of the month's file (newest first). Returns the file, or None."""
    if not changes:
        return None
    month = date[:7]
    path = directory / f"{month}.md"
    header = f"# Upstream changelog {month}\n\n"
    existing = path.read_text() if path.exists() else header
    if not existing.startswith(header):
        existing = header + existing
    directory.mkdir(parents=True, exist_ok=True)
    path.write_text(header + render_entries(changes, date) + "\n" + existing[len(header):])
    return path


# -----------------------------------------------------------------------
# INDEX.md
# -----------------------------------------------------------------------

def _entry_lines(e: dict) -> list[str]:
    flags = (e.get("state") or {}).get("flags") or []
    line = f"- [{e['repo']}](https://github.com/{e['repo']}) ({e['verdict']})"
    if flags:
        line += " - **" + ", ".join(flags) + "**"
    if e.get("notes"):
        line += f" - {e['notes']}"
    lines = [line]
    if e.get("skill_or_plugin_paths"):
        lines.append("  - paths: " + ", ".join(f"`{p}`" for p in e["skill_or_plugin_paths"]))
    return lines


def render_index(data: dict) -> str:
    repos = data["repos"]
    watched = [e for e in repos if e.get("verdict") in VERDICT_ORDER]
    skipped = sorted((e for e in repos if e.get("verdict") == "skip"), key=lambda e: e["repo"].lower())
    stubs = sorted((e for e in repos if e.get("verdict") is None), key=lambda e: e["repo"].lower())

    groups: dict[str, list[dict]] = {}
    for e in watched:
        for tag in e.get("use_contexts") or ["Untagged"]:
            groups.setdefault(tag, []).append(e)

    lines = [
        "<!-- Generated by the skills index sync. Do not edit; edit tracked.yml. -->",
        "",
        "# Skills index",
        "",
        "Curated repos by use-context. See also the [upstream changelog](changelog/).",
        "",
    ]
    for tag in sorted(groups, key=lambda t: (t == "Untagged", t)):
        lines += [f"## {tag}", ""]
        for e in _by_verdict(groups[tag]):
            lines += _entry_lines(e)
        lines.append("")
    if skipped:
        lines += [f"## Skipped ({len(skipped)})", ""] + [f"- {e['repo']}" for e in skipped] + [""]
    lines += [f"## Stubs ({len(stubs)})", "", "Starred, not yet reviewed.", ""]
    lines += [f"- {e['repo']}" for e in stubs]
    return "\n".join(lines) + "\n"


def write_index(data: dict, path: Path = INDEX_FILE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_index(data))


def main():
    tracked = ROOT / "tracked.yml"
    write_index(yaml.safe_load(tracked.read_text()) or {"repos": []})
    print(f"Wrote {INDEX_FILE}", file=sys.stderr)


if __name__ == "__main__":
    main()
